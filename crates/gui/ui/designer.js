/// The divider between the editor canvas and the preview band: drag it
/// and the balance is yours, remembered across sessions. A fixed split
/// always starved one side or the other.
function initSplitter() {
  const bar = $("dz-splitter");
  const box = $("dz-preview-box");
  const KEY = "rhythr.designer.previewH";
  const saved = Number(localStorage.getItem(KEY));
  if (saved >= 120 && saved <= window.innerHeight * 0.7) {
    box.style.flexBasis = `${saved}px`;
  }
  let startY = 0;
  let startH = 0;
  bar.addEventListener("pointerdown", (e) => {
    startY = e.clientY;
    startH = box.getBoundingClientRect().height;
    bar.setPointerCapture(e.pointerId);
  });
  bar.addEventListener("pointermove", (e) => {
    if (!bar.hasPointerCapture(e.pointerId)) return;
    const h = Math.max(120, Math.min(window.innerHeight * 0.7, startH - (e.clientY - startY)));
    box.style.flexBasis = `${h}px`;
  });
  bar.addEventListener("pointerup", (e) => {
    if (!bar.hasPointerCapture(e.pointerId)) return;
    bar.releasePointerCapture(e.pointerId);
    localStorage.setItem(KEY, String(Math.round(box.getBoundingClientRect().height)));
  });
}

// ---- point editing (freeform only)

let dragging = -1;
let selected = -1;

/// Snapping: grid intersections (0.1), the axes and the unit box edges,
/// judged in SCREEN pixels so zooming in naturally loosens the pull.
/// Exact regular geometry stops taking surgeon hands.
function snapPoint(wx, wy) {
  if (!$("dz-snap").checked) return [wx, wy];
  // Capped at a third of a grid cell: with a small canvas (or zoomed
  // out) a fixed pixel radius would cover half the cell and snap
  // EVERYTHING, making free placement impossible.
  const RADIUS = Math.min(7, 0.1 * UNIT * view.z * 0.35);
  const snap1 = (v) => {
    const candidates = [Math.round(v * 10) / 10, 0, 1, -1];
    let best = v;
    let bd = Infinity;
    for (const c of candidates) {
      const d = Math.abs(v - c) * UNIT * view.z;
      if (d < RADIUS && d < bd) {
        bd = d;
        best = c;
      }
    }
    return best;
  };
  return [snap1(wx), snap1(wy)];
}

function pointAt(mx, my) {
  if (!free) return -1;
  for (let i = 0; i < free.length; i++) {
    const [x, y] = toPx([free[i].x, free[i].y]);
    if (Math.hypot(mx - x, my - y) < 12) return i;
  }
  return -1;
}

/// Angle folded into the editable wedge, for inserting and dragging under
/// symmetry: whatever wedge the mouse is in, the edit lands in wedge 0.
function foldToWedge(x, y) {
  if (!free || (symmetry <= 1 && !mirror)) return [x, y];
  const a = Math.atan2(y, x);
  const wedge = wedgeAngle();
  let folded = ((a % ((Math.PI * 2) / symmetry)) + (Math.PI * 2) / symmetry) % ((Math.PI * 2) / symmetry);
  // Mirror halves the sector: the reflected half folds back onto the
  // editable half.
  if (mirror && folded > wedge) folded = (Math.PI * 2) / symmetry - folded;
  const r = Math.hypot(x, y);
  return [r * Math.cos(folded), r * Math.sin(folded)];
}

cv.addEventListener("pointerdown", (e) => {
  const rect0 = cv.getBoundingClientRect();
  if (e.button === 1 || (e.button === 0 && spaceDown)) {
    panning = {
      px: e.clientX - rect0.left,
      py: e.clientY - rect0.top,
      cx: view.cx,
      cy: view.cy,
    };
    cv.style.cursor = "grabbing";
    cv.setPointerCapture(e.pointerId);
    e.preventDefault();
    return;
  }
  if (!free) return;
  // Left button only: middle and side buttons were adding points too.
  if (e.button !== 0) return;
  const rect = cv.getBoundingClientRect();
  const mx = e.clientX - rect.left;
  const my = e.clientY - rect.top;
  const hit = pointAt(mx, my);
  if (hit >= 0) {
    commit(0);
    selected = hit;
    dragging = hit;
    cv.setPointerCapture(e.pointerId);
    draw();
    return;
  }
  // Insert only when the click actually lands NEAR the outline: a click
  // in empty space (or outside the note entirely) is not a request for a
  // point there.
  if (plan?.shapes?.length) {
    let best = Infinity;
    const inv = 1 / (plan.scale || 1);
    const near = (list) => {
      const n = list.length;
      for (let i = 0; i < n; i++) {
        const [ax, ay] = toPx([list[i][0] * inv, list[i][1] * inv]);
        const [bx, by] = toPx([list[(i + 1) % n][0] * inv, list[(i + 1) % n][1] * inv]);
        const dx = bx - ax, dy = by - ay;
        const len2 = dx * dx + dy * dy || 1e-9;
        const t = Math.max(0, Math.min(1, ((mx - ax) * dx + (my - ay) * dy) / len2));
        const qx = ax + t * dx, qy = ay + t * dy;
        best = Math.min(best, Math.hypot(mx - qx, my - qy));
      }
    };
    for (const sh of plan.shapes) {
      near(sh.outer);
      for (const h of sh.holes) near(h);
    }
    if (best > 18) return;
  }
  // Click near the outline: insert a point there (folded into the wedge).
  commit(0);
  let [wx, wy] = toWorld(mx, my);
  [wx, wy] = foldToWedge(wx, wy);
  [wx, wy] = snapPoint(...clampUnit(wx, wy));
  // Insert in angular order so the wedge stays a simple arc of points.
  // Angles normalised to [0, 2pi): atan2 goes negative below the x-axis,
  // and comparing raw values put every lower-half click at index 0,
  // scrambling the outline in no-symmetry mode.
  const norm = (a) => ((a % (Math.PI * 2)) + Math.PI * 2) % (Math.PI * 2);
  const ang = norm(Math.atan2(wy, wx));
  let at = free.length;
  for (let i = 0; i < free.length; i++) {
    if (norm(Math.atan2(free[i].y, free[i].x)) > ang) {
      at = i;
      break;
    }
  }
  free.splice(at, 0, { x: wx, y: wy, smooth: true });
  dragging = at;
  selected = at;
  cv.setPointerCapture(e.pointerId);
  scheduleAll();
});

cv.addEventListener("pointermove", (e) => {
  const rect = cv.getBoundingClientRect();
  const mx = e.clientX - rect.left;
  const my = e.clientY - rect.top;
  if (panning) {
    view.cx = panning.cx - (mx - panning.px) / (UNIT * view.z);
    view.cy = panning.cy + (my - panning.py) / (UNIT * view.z);
    draw();
    return;
  }
  if (dragging < 0) {
    // Hover feedback: the cursor names the action before the click.
    if (spaceDown) {
      cv.style.cursor = "grab";
    } else if (free && pointAt(mx, my) >= 0) {
      cv.style.cursor = "grab";
    } else if (free) {
      cv.style.cursor = "crosshair";
    } else {
      cv.style.cursor = "default";
    }
    return;
  }
  if (!free) return;
  let [wx, wy] = toWorld(mx, my);
  // Clamp into the wedge instead of folding: folding teleports a point
  // sitting near the boundary to the wedge's far side the moment the
  // cursor slips across, which reads as the point jumping away.
  if (free && (symmetry > 1 || mirror)) {
    const wedge = wedgeAngle();
    let a = Math.atan2(wy, wx);
    if (a < 0) a += Math.PI * 2;
    a = Math.min(a, wedge);
    const rr = Math.hypot(wx, wy);
    wx = rr * Math.cos(a);
    wy = rr * Math.sin(a);
  }
  [wx, wy] = snapPoint(...clampUnit(wx, wy));
  free[dragging] = { ...free[dragging], x: wx, y: wy };
  scheduleAll();
});

cv.addEventListener("pointerup", () => {
  dragging = -1;
  if (panning) {
    panning = null;
    cv.style.cursor = "default";
  }
});

cv.addEventListener("dblclick", (e) => {
  if (!free) return;
  const rect = cv.getBoundingClientRect();
  const hit = pointAt(e.clientX - rect.left, e.clientY - rect.top);
  if (hit >= 0) {
    commit(0);
    free[hit].smooth = !free[hit].smooth;
    scheduleAll();
  }
});

cv.addEventListener("contextmenu", (e) => {
  e.preventDefault();
  if (!free || free.length <= 3) return;
  const rect = cv.getBoundingClientRect();
  const hit = pointAt(e.clientX - rect.left, e.clientY - rect.top);
  if (hit >= 0) {
    commit(0);
    free.splice(hit, 1);
    // A removal invalidates whatever a concurrent left-drag was holding.
    dragging = -1;
    selected = -1;
    scheduleAll();
  }
});

// Keyboard editing: arrows nudge the selected point, Delete removes it,
// Escape deselects. Undo/redo lives on the document level below.
window.addEventListener("keydown", (e) => {
  if (isTyping()) return;
  const mod = e.ctrlKey || e.metaKey;
  if (mod && e.key.toLowerCase() === "z") {
    e.preventDefault();
    if (e.shiftKey) redo();
    else undo();
    return;
  }
  if (mod && e.key.toLowerCase() === "y") {
    e.preventDefault();
    redo();
    return;
  }
  if (!free) return;
  if (e.key === "Escape") {
    selected = -1;
    draw();
    return;
  }
  if (selected < 0 || selected >= free.length) return;
  if (e.key === "Delete" || e.key === "Backspace") {
    if (free.length <= 3) return;
    commit(0);
    free.splice(selected, 1);
    selected = -1;
    scheduleAll();
    e.preventDefault();
    return;
  }
  const step = e.shiftKey ? 0.05 : 0.01;
  const dir = {
    ArrowLeft: [-step, 0],
    ArrowRight: [step, 0],
    ArrowUp: [0, step],
    ArrowDown: [0, -step],
  }[e.key];
  if (!dir) return;
  commit(600);
  let [wx, wy] = [free[selected].x + dir[0], free[selected].y + dir[1]];
  [wx, wy] = clampUnit(wx, wy);
  free[selected] = { ...free[selected], x: wx, y: wy };
  scheduleAll();
  e.preventDefault();
});


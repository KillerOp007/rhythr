// Note designer: an outline editor whose output is a real mesh skin.
//
// Three layers of shaping, all funnelling into ONE closed outline:
//   1. sliders (base shape, rounding, hollow, depth)
//   2. modifiers (waves, twist) applied to the slider shape
//   3. freeform: the current outline frozen into draggable control
//      points, with radial symmetry so one edited wedge repeats
// The backend turns the outline into geometry and renders the preview
// with the actual renderer, so the picture is the truth, not a sketch.

const invoke = window.__TAURI__.core.invoke;
const dialog = window.__TAURI__.dialog;

const $ = (id) => document.getElementById(id);

// ------------------------------------------------------------ state

const P = {
  shape: "circle",
  n: 6,
  round: 0.3,
  hollow: true,
  thick: 0.22,
  depth: 0.05,
  waves: 0,
  waveDepth: 0.25,
  waveform: "sine",
  twist: 0,
};

/// The wave shape: soft, spiky or blocky, all with the same count/depth.
function waveFn(k) {
  const s = Math.sin(k);
  if (P.waveform === "spike") return (2 / Math.PI) * Math.asin(s);
  if (P.waveform === "pulse") return Math.tanh(3 * s) / Math.tanh(3);
  return s;
}
// Freeform mode: control points in the unit plane, each {x, y, smooth}.
// With symmetry s > 1 the points cover ONE wedge of 2π/s and the rest is
// generated; with s == 1 they are the whole outline.
let free = null;
let symmetry = 4;
// Mirror mode: each symmetry sector is the wedge PLUS its reflection, so
// shapes with reflection axes (hearts, shields, crowns) become editable,
// which pure rotation can never produce.
let mirror = false;
let colors = ["#ffffff", "#a2e0ff", "#a2e0ff"]; // the game's Arctic

/// The editable wedge's angular size: mirroring halves it, because the
/// other half of every sector is generated by reflection.
function wedgeAngle() {
  return (Math.PI * 2) / symmetry / (mirror ? 2 : 1);
}

// ---- the design document: one JSON string carrying the WHOLE editable
// state. Undo, autosave and the design file all speak this format, so
// they can never disagree about what a design is.
const DOC_KEY = "rhythr.designer.doc";
const RECENT_KEY = "rhythr.designer.recent";
let DEFAULT_DOC = null;
const undoStack = [];
const redoStack = [];
let lastSnap = -1e9;
let saveTimer = null;

function docState() {
  return JSON.stringify({ P: { ...P }, free, symmetry, mirror, colors });
}

function applyDocRaw(json) {
  const d = JSON.parse(json);
  Object.assign(P, d.P || {});
  free = Array.isArray(d.free) ? d.free : null;
  symmetry = Number(d.symmetry) || 4;
  mirror = !!d.mirror;
  colors = Array.isArray(d.colors) && d.colors.length ? d.colors : ["#ffffff"];
  selected = -1;
  dragging = -1;
  renderColors();
  syncControls();
  scheduleAll();
}

/// Snapshot BEFORE a mutation. A positive coalesce keeps a continuous
/// gesture (slider drag, arrow-key repeat) to one undo step: the window
/// slides with every call and only an idle gap opens a new step.
function commit(coalesceMs = 350) {
  const now = performance.now();
  if (coalesceMs > 0 && now - lastSnap < coalesceMs) {
    lastSnap = now;
    return;
  }
  lastSnap = now;
  undoStack.push(docState());
  if (undoStack.length > 120) undoStack.shift();
  redoStack.length = 0;
}

function undo() {
  if (!undoStack.length) return;
  redoStack.push(docState());
  applyDocRaw(undoStack.pop());
}

function redo() {
  if (!redoStack.length) return;
  undoStack.push(docState());
  applyDocRaw(redoStack.pop());
}

function recentList() {
  try {
    return JSON.parse(localStorage.getItem(RECENT_KEY)) || [];
  } catch {
    return [];
  }
}

function addRecent(path) {
  const list = recentList().filter((x) => x !== path);
  list.unshift(path);
  localStorage.setItem(RECENT_KEY, JSON.stringify(list.slice(0, 8)));
  renderRecent();
}

function renderRecent() {
  const sel = $("dz-recent");
  while (sel.options.length > 1) sel.remove(1);
  for (const path of recentList()) {
    const opt = document.createElement("option");
    opt.value = path;
    opt.textContent = path.split(/[\\/]/).pop();
    opt.title = path;
    sel.appendChild(opt);
  }
}

async function loadDocFrom(path) {
  try {
    const json = await invoke("designer_doc_load", { path });
    commit(0);
    applyDocRaw(json);
    addRecent(path);
    setStatus(`Design loaded: ${path}`);
  } catch (e) {
    setStatus(String(e), true);
  }
}

// ------------------------------------------------------------ outline

/// Slider outline: radius as a function of angle, sampled densely.
function paramOutline(samples = 160) {
  const pts = [];
  const tw = (P.twist * Math.PI) / 180;
  for (let i = 0; i < samples; i++) {
    const th = (i / samples) * Math.PI * 2;
    let r;
    if (P.shape === "circle") {
      r = 1;
    } else {
      // Regular N-gon radius, blended toward the circle by the rounding
      // slider. A square is the 4-gon turned 45° so its sides sit flat.
      const n = P.shape === "square" ? 4 : P.n;
      const off = P.shape === "square" ? Math.PI / 4 : 0;
      const a = ((th + off + tw) % (Math.PI * 2 / n) + Math.PI * 2 / n) % (Math.PI * 2 / n);
      const ngon = Math.cos(Math.PI / n) / Math.cos(a - Math.PI / n);
      r = ngon + (1 - ngon) * P.round;
    }
    if (P.waves > 0) {
      r *= 1 + P.waveDepth * waveFn(P.waves * (th + tw));
    }
    pts.push([r * Math.cos(th), r * Math.sin(th)]);
  }
  // Waves can push the radius past the unit cap; scale the whole shape
  // back so the drawn outline IS the exported one, never larger.
  const max = pts.reduce((m, p) => Math.max(m, Math.abs(p[0]), Math.abs(p[1])), 0);
  if (max > 1) {
    for (const p of pts) {
      p[0] /= max;
      p[1] /= max;
    }
  }
  return pts;
}

/// Expands the freeform control points through the symmetry into the full
/// control loop. The BACKEND turns this into a curve (spline flattening
/// with adaptive tolerance), so the editor never samples curves itself.
function controlLoop() {
  // One sector: the wedge, preceded by its x-axis reflection when mirror
  // is on (reversed so the loop keeps running counterclockwise). The
  // backend deduplicates points that land exactly on the axis.
  const sector = mirror
    ? [
        ...free
          .slice()
          .reverse()
          .map((p) => ({ x: p.x, y: -p.y, smooth: p.smooth })),
        ...free,
      ]
    : free;
  const ctrl = [];
  for (let s = 0; s < symmetry; s++) {
    const a = (s * Math.PI * 2) / symmetry;
    const ca = Math.cos(a), sa = Math.sin(a);
    for (const p of sector) {
      ctrl.push({ x: p.x * ca - p.y * sa, y: p.x * sa + p.y * ca, smooth: p.smooth });
    }
  }
  return ctrl.length >= 3 ? ctrl : null;
}



const SLIDERS = [
  ["dz-n", () => P.n, (v) => (P.n = v), (v) => String(v)],
  ["dz-round", () => P.round * 100, (v) => (P.round = v / 100), (v) => `${v}%`],
  ["dz-thick", () => P.thick * 100, (v) => (P.thick = v / 100), (v) => `${v}%`],
  ["dz-depth", () => P.depth * 100, (v) => (P.depth = v / 100), (v) => `${v}%`],
  ["dz-waves", () => P.waves, (v) => (P.waves = v), (v) => String(v)],
  ["dz-wavedepth", () => P.waveDepth * 100, (v) => (P.waveDepth = v / 100), (v) => `${v}%`],
  ["dz-twist", () => P.twist, (v) => (P.twist = v), (v) => `${v}°`],
];

function bindSlider(id, get, set, fmt) {
  const el = $(id);
  el.addEventListener("input", () => {
    commit(600);
    set(Number(el.value));
    $(`${id}-val`) && ($(`${id}-val`).textContent = fmt(Number(el.value)));
    scheduleAll();
  });
  $(`${id}-val`) && ($(`${id}-val`).textContent = fmt(get()));
}

/// Writes the document state back into every control, so undo, load and
/// reset always leave the panel telling the truth.
function syncControls() {
  $("dz-shape").value = P.shape;
  $("dz-n-row").hidden = P.shape !== "ngon";
  $("dz-hollow").checked = P.hollow;
  $("dz-thick-row").hidden = !P.hollow;
  $("dz-waveform").value = P.waveform;
  for (const [id, get, , fmt] of SLIDERS) {
    $(id).value = get();
    $(`${id}-val`) && ($(`${id}-val`).textContent = fmt(Math.round(get())));
  }
  $("dz-symmetry").value = String(symmetry);
  $("dz-symmetry").disabled = !!free;
  $("dz-mirror").checked = mirror;
  $("dz-back-params").hidden = !free;
  $("dz-to-points").hidden = !!free;
}

function wireControls() {
  $("dz-shape").addEventListener("change", () => {
    commit(0);
    P.shape = $("dz-shape").value;
    $("dz-n-row").hidden = P.shape !== "ngon";
    scheduleAll();
  });
  for (const [id, get, set, fmt] of SLIDERS) bindSlider(id, get, set, fmt);
  $("dz-waveform").addEventListener("change", () => {
    commit(0);
    P.waveform = $("dz-waveform").value;
    scheduleAll();
  });
  $("dz-hollow").addEventListener("change", () => {
    commit(0);
    P.hollow = $("dz-hollow").checked;
    $("dz-thick-row").hidden = !P.hollow;
    scheduleAll();
  });

  $("dz-to-points").addEventListener("click", () => {
    commit(0);
    // A five-wave shape frozen into four-fold symmetry is a different
    // shape: converting adopts the wave count as the symmetry when waves
    // are active, so the points reproduce what is on screen.
    if (P.waves >= 2 && P.waves <= 12) {
      const sel = $("dz-symmetry");
      const fit = [...sel.options].some((o) => Number(o.value) === P.waves)
        ? P.waves
        : 1;
      symmetry = fit;
      sel.value = String(fit);
    }
    // Freeze the current outline into a handful of control points per
    // wedge: dense sampling would give 160 handles nobody wants to drag.
    // When the wave count fits no symmetry option, the whole outline
    // converts at a density that still resolves every wave, instead of
    // the old eight-points-total collapse.
    const samples = symmetry > 1
      ? symmetry * 8
      : Math.min(96, Math.max(24, (P.waves || 3) * 8));
    const pts = paramOutline(samples);
    const per = pts.length / symmetry;
    mirror = false;
    free = pts.slice(0, per).map(([x, y]) => ({ x, y, smooth: true }));
    $("dz-back-params").hidden = false;
    $("dz-to-points").hidden = true;
    $("dz-symmetry").disabled = true; // point set is per-wedge now
    scheduleAll();
  });
  $("dz-back-params").addEventListener("click", () => {
    commit(0);
    free = null;
    selected = -1;
    $("dz-back-params").hidden = true;
    $("dz-to-points").hidden = false;
    $("dz-symmetry").disabled = false;
    scheduleAll();
  });
  $("dz-symmetry").addEventListener("change", () => {
    commit(0);
    symmetry = Number($("dz-symmetry").value);
    scheduleAll();
  });
  $("dz-mirror").addEventListener("change", () => {
    commit(0);
    mirror = $("dz-mirror").checked;
    scheduleAll();
  });
  for (const btn of document.querySelectorAll("#dz-presets button")) {
    btn.addEventListener("click", () => {
      const preset = PRESETS[btn.dataset.preset];
      if (!preset) return;
      commit(0);
      free = preset.points.map((p) => ({ ...p }));
      symmetry = preset.symmetry;
      mirror = !!preset.mirror;
      selected = -1;
      syncControls();
      scheduleAll();
    });
  }

  $("dz-color-add").addEventListener("click", () => {
    if (colors.length >= 12) return;
    commit(0);
    colors.push("#ffffff");
    renderColors();
    scheduleAll();
  });
  $("dz-reset").addEventListener("click", () => {
    commit(0);
    localStorage.removeItem(DOC_KEY);
    if (DEFAULT_DOC) {
      applyDocRaw(DEFAULT_DOC);
      resetView();
    } else {
      location.reload();
    }
  });
  $("dz-view-reset").addEventListener("click", resetView);
  $("dz-doc-save").addEventListener("click", async () => {
    const path = await dialog.save({
      defaultPath: "my-note.rhsd",
      filters: [{ name: "rhythr note design", extensions: ["rhsd"] }],
    });
    if (!path) return;
    try {
      await invoke("designer_doc_save", { path, json: docState() });
      addRecent(path);
      setStatus(`Design saved: ${path}`);
    } catch (e) {
      setStatus(String(e), true);
    }
  });
  $("dz-doc-load").addEventListener("click", async () => {
    const path = await dialog.open({
      multiple: false,
      filters: [{ name: "rhythr note design", extensions: ["rhsd"] }],
    });
    if (!path || Array.isArray(path)) return;
    loadDocFrom(path);
  });
  $("dz-recent").addEventListener("change", () => {
    const path = $("dz-recent").value;
    $("dz-recent").value = "";
    if (path) loadDocFrom(path);
  });
  $("dz-save").addEventListener("click", async () => {
    const path = await dialog.save({
      defaultPath: "my-note.rhs",
      filters: [{ name: "Rhythia skin", extensions: ["rhs"] }],
    });
    if (!path) return;
    try {
      const saved = await invoke("designer_export", { shape: shapePayload(), path });
      setStatus(`Saved: ${saved} - load it via Config in the main window, or import it in the game.`);
    } catch (e) {
      setStatus(String(e), true);
    }
  });
}

let dragColorIdx = -1;

function renderColors() {
  const box = $("dz-colors");
  box.innerHTML = "";
  colors.forEach((c, i) => {
    const row = document.createElement("div");
    row.className = "dz-color-row";
    // The order IS the beat order in the preview loop, so it is worth
    // rearranging: drag a row where you want its colour to land.
    row.draggable = true;
    const grip = document.createElement("span");
    grip.className = "grip";
    grip.textContent = "⠿";
    grip.title = "Drag to reorder: the notes play the colors in this order";
    row.appendChild(grip);
    row.addEventListener("dragstart", () => {
      dragColorIdx = i;
      row.classList.add("dragging");
    });
    row.addEventListener("dragend", () => {
      dragColorIdx = -1;
      row.classList.remove("dragging");
    });
    row.addEventListener("dragover", (e) => e.preventDefault());
    row.addEventListener("drop", (e) => {
      e.preventDefault();
      if (dragColorIdx < 0 || dragColorIdx === i) return;
      commit(0);
      const [moved] = colors.splice(dragColorIdx, 1);
      colors.splice(i, 0, moved);
      dragColorIdx = -1;
      renderColors();
      scheduleAll();
    });
    const pick = document.createElement("input");
    pick.type = "color";
    pick.value = c;
    const hex = document.createElement("input");
    hex.type = "text";
    hex.className = "mono hex";
    hex.value = c;
    const del = document.createElement("button");
    del.className = "btn small ghost";
    del.textContent = "✕";
    del.title = "Remove this color";
    pick.addEventListener("input", () => {
      commit(600);
      colors[i] = pick.value;
      hex.value = pick.value;
      scheduleAll();
    });
    hex.addEventListener("change", () => {
      const v = hex.value.trim();
      if (/^#[0-9a-fA-F]{6}$/.test(v)) {
        commit(0);
        colors[i] = v;
        pick.value = v;
        scheduleAll();
      } else {
        hex.value = colors[i];
      }
    });
    del.addEventListener("click", () => {
      if (colors.length <= 1) return;
      commit(0);
      colors.splice(i, 1);
      renderColors();
      scheduleAll();
    });
    row.append(pick, hex, del);
    box.appendChild(row);
  });
}

